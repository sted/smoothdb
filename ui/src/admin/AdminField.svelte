<script lang="ts">
    import type { AdminContext, FieldDef, Item } from "./entities";
    import { columnNames, roleNames, schemaNames, tableNames } from "./refs.svelte";
    import Icon from "../components/Icon.svelte";

    // The control of one field of an admin object, as compact as a row of the
    // side panel. The value is a string, a boolean or a list of strings.
    interface Props {
        id: string;
        field: FieldDef;
        ctx: AdminContext;
        // the whole form, for a field that depends on another
        values: Item;
        value: any;
        disabled?: boolean;
        invalid?: boolean;
        autofocus?: boolean;
    }
    let { id, field, ctx, values, value = $bindable(), disabled = false, invalid = false, autofocus = false }: Props = $props();

    let options: string[] = $state([]);
    let el: HTMLElement | undefined = $state();
    let focused = $state(false);

    $effect(() => {
        if (field.kind === "role" || field.kind === "roles") roleNames().then((r) => (options = r));
        else if (field.kind === "schema") schemaNames(ctx.db).then((s) => (options = s));
        else if (field.kind === "select" || field.kind === "multi") options = field.options ?? [];
        else if (field.kind === "table") tableNames(ctx.db).then((t) => (options = t));
        else if (field.kind === "columns") columnNames(ctx.db, ctx.schema, ctx.table).then((c) => (options = c));
        else if (field.kind === "refcolumns") {
            // the columns of the table the other field names; none until it has one
            const st: string = values[field.from ?? ""] ?? "";
            const dot = st.indexOf(".");
            if (dot < 0) options = [];
            else columnNames(ctx.db, st.slice(0, dot), st.slice(dot + 1)).then((c) => (options = c));
        }
    });

    $effect(() => {
        if (autofocus && el) el.focus();
    });

    // a value that the list does not hold yet (a role created elsewhere) stays selectable
    let choices = $derived(value && typeof value === "string" && !options.includes(value) ? [value, ...options] : options);

    // the types a column takes most often, in groups; any other type is
    // typed in after "Other type…"
    const typeGroups: [string, string[]][] = [
        ["Text", ["text", "varchar(255)", "char(1)", "uuid"]],
        ["Numbers", ["integer", "bigint", "smallint", "numeric(10,2)", "real", "double precision"]],
        ["Date and time", ["date", "timestamptz", "timestamp", "time", "interval"]],
        ["Other", ["boolean", "jsonb", "json", "bytea", "text[]", "integer[]"]],
        ["Identity", ["bigint generated by default as identity"]],
    ];
    const OTHER = "\u0000other";
    let groups = $derived(field.options ? ([["", field.options]] as [string, string[]][]) : typeGroups);
    let known = $derived(groups.flatMap(([, t]) => t));
    // a value out of the list is typed in; it starts so when the column has one
    let customType = $state(false);
    $effect.pre(() => {
        if (field.kind === "type" && value && !known.includes(value)) customType = true;
    });
    let typeChoice = $derived(customType ? OTHER : (value ?? ""));
    function chooseType(v: string) {
        if (v === OTHER) {
            customType = true;
            queueMicrotask(() => el?.focus());
        } else value = v;
    }

    // a list field: roles, columns
    let multi = $derived(field.kind === "roles" || field.kind === "columns" || field.kind === "refcolumns" || field.kind === "multi");
    let roles: string[] = $derived(Array.isArray(value) ? value : []);
    let adding = $state("");

    function addRole(r: string) {
        if (r && !roles.includes(r)) value = [...roles, r];
        adding = "";
    }
    let addLabel = $derived(
        field.kind === "roles" ? (roles.length ? "Add a role" : "PUBLIC (all roles)") : field.kind === "refcolumns" && !options.length ? "Choose the table first" : field.kind === "multi" ? "Add" : "Add a column",
    );
    let addable = $derived((field.kind === "roles" ? ["public", ...options] : options).filter((o) => !roles.includes(o)));

    let rows = $derived(focused ? Math.min(14, Math.max(4, String(value ?? "").split("\n").length + 1)) : Math.min(6, Math.max(2, String(value ?? "").split("\n").length)));
</script>

<div class="admin-field" class:invalid>
    {#if field.kind === "bool"}
        <label class="toggle">
            <input {id} type="checkbox" class="switch" bind:checked={value} {disabled} />
            <span>{value ? "Yes" : "No"}</span>
        </label>
    {:else if field.kind === "role" || field.kind === "schema" || field.kind === "select" || field.kind === "table"}
        <select {id} class="input" bind:this={el} bind:value {disabled}>
            {#if field.kind !== "select"}<option value="">{field.emptyLabel ?? (field.kind === "role" ? "Current role" : field.kind === "table" ? "Choose a table" : "Default")}</option>{/if}
            {#each choices as o}<option value={o}>{o}</option>{/each}
        </select>
    {:else if multi}
        <div class="roles">
            {#each roles as r}
                <span class="chip mono">
                    {r}
                    <button type="button" aria-label={`Remove ${r}`} {disabled} onclick={() => (value = roles.filter((x) => x !== r))}>
                        <Icon name="close" size={11} />
                    </button>
                </span>
            {/each}
            <select
                {id}
                class="input add"
                bind:value={adding}
                {disabled}
                onchange={() => addRole(adding)}
                aria-label={`Add to ${field.label}`}
            >
                <option value="">{addLabel}</option>
                {#each addable as o}<option value={o}>{o}</option>{/each}
            </select>
        </div>
    {:else if field.kind === "type" && !customType}
        <select {id} class="input mono" bind:this={el} value={typeChoice} onchange={(e) => chooseType(e.currentTarget.value)} {disabled}>
            <option value="" disabled>Choose a type</option>
            {#each groups as [label, types]}
                {#if label}
                    <optgroup {label}>{#each types as t}<option value={t}>{t}</option>{/each}</optgroup>
                {:else}
                    {#each types as t}<option value={t}>{t}</option>{/each}
                {/if}
            {/each}
            <option value={OTHER}>Other type…</option>
        </select>
    {:else if field.kind === "type"}
        <div class="typed">
            <input
                {id}
                bind:this={el}
                class="input mono"
                bind:value
                placeholder={field.placeholder ?? "Any PostgreSQL type"}
                {disabled}
                autocomplete="off"
                spellcheck="false"
            />
            <button
                type="button"
                class="btn btn-sm btn-ghost"
                title="Choose from the list"
                {disabled}
                onclick={() => {
                    customType = false;
                    if (!known.includes(value)) value = "";
                }}><Icon name="expand-up-down" size={13} /></button
            >
        </div>
    {:else if field.kind === "sql" && field.multiline}
        <textarea
            {id}
            bind:this={el}
            class="input mono"
            {rows}
            bind:value
            placeholder={field.placeholder}
            {disabled}
            spellcheck="false"
            onfocus={() => (focused = true)}
            onblur={() => (focused = false)}
        ></textarea>
    {:else}
        <input
            {id}
            bind:this={el}
            class="input"
            class:mono={field.kind !== "text"}
            title={field.kind === "args" ? field.help : undefined}
            bind:value
            placeholder={field.placeholder}
            {disabled}
            autocomplete="off"
            spellcheck="false"
        />
    {/if}
</div>

